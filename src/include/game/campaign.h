/**
 * One leg of a merged mission, generated by tools/merge/setupmerge.py from the
 * level's setup source (src/game/merged/legs_*.inc.c).
 */
struct campaignleg {
	s32 stagenum;    // the original level
	u8 objfirst;     // its objectives in the merged list
	u8 objcount;
	u16 spawnpad;    // where the leg begins, in the merged pads file
	s16 world;       // which geometry world of the merged background
	s16 roomoffset;  // added to the level's room numbers in that world
	s16 chrbase;     // added to the level's character numbers
	s16 tagbase;     // added to the level's object tags
	s16 offset[3];   // where the level's world sits in the merged one (x, y, z)
	u8 outfit;
	s8 numweapons;
	u8 weapons[6];   // what the level's intro handed out
	s8 numammo;
	struct {
		u8 type;
		u16 qty;
	} ammo[6];
	u16 outrolist;   // the AI list whose end is the leg's success exit, 0 for the final leg
};

// A door two legs place is one door; when a leg begins, the door takes the lock
// that leg's setup gave it (its key bits and its one-way flags).
struct campaignlock {
	s8 leg;          // -1 ends the table
	u16 cmdindex;    // the door's command in the merged setup
	u32 keyflags;
	u32 lockflags;   // OBJFLAG2_LOCKEDFRONT and OBJFLAG2_LOCKEDBACK
};

