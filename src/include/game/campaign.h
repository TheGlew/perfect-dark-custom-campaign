/**
 * Continuous campaign (PC port only).
 *
 * With Campaign.Continuous on, a completed solo mission rolls straight into
 * the next one: no end screen, no "Next Mission" menu. Joanna keeps her guns,
 * ammo, health and shield between missions, and dying restarts the current
 * mission directly instead of showing the failure screen.
 *
 * Merged missions: three of the game's missions are one level each here, built
 * from their levels' data by tools/merge (dataDyne: Defection, Investigation
 * and Extraction; Chicago and the G5 Building; Area 51: Infiltration, Rescue
 * and Escape). Each original level is a "leg" of the merged mission. The legs'
 * scripts all run in the one world; the campaign hands over from leg to leg at
 * the joint the leg's own success exit became, keeps a stage-flag word per leg,
 * lists every leg's objectives, and restarts a dead player at the current leg's
 * joint with the kit held there.
 *
 * Nothing here runs in Combat Simulator, co-op or counter-op, and nothing runs
 * at all while Campaign.Continuous is off.
 */

// pd.ini [Campaign]
extern s32 g_CampaignContinuous;
